#!/usr/bin/env python3
"""Generate the spec-driven Stripe API layer from the vendored OpenAPI spec.

    make generate            # = uv run --no-project python scripts/generate_api.py

Reads ``spec/stripe-openapi/spec3.json`` (github.com/stripe/openapi, MIT; the pinned commit
is in ``spec/stripe-openapi/source.json``) and writes, deterministically:

* ``src/stripe/generated/endpoints.json`` — one descriptor per generated table function
  (schema, name, endpoint, columns with their extraction kind, pushdown parameters,
  arguments, fan-out) plus the GET path templates ``api.get`` accepts. The worker turns
  each descriptor into a table function at start-up (``src/stripe/api.ts``); it never
  reads the 8 MB spec at run time.
* ``src/stripe/generated/EXCLUDED.md`` — every GET endpoint deliberately not generated,
  with the reason.
* the generated block of ``vgi-agent-tests.yaml`` (one grader per generated function).

Every GET endpoint of the spec is accounted for: a list endpoint becomes a table function
(nested lists fan out over their parent), a singleton GET becomes a one-row function, a
retrieve-by-id GET becomes ``WHERE id = …`` pushdown on its list function (or a function
of its own when Stripe has no list for it), and the rest are listed in EXCLUDED.md.
``--check`` exits 1 if the committed output differs from what the spec generates.
"""

