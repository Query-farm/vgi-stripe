def pick_example(ep: dict) -> dict:
    """A deterministic analytical example and an agent task for one endpoint."""
    q = f"stripe.{ep['schema']}.{ep['name']}"
    cols = {c["n"]: c for c in ep["columns"]}
    fan = ep["fanout"]
    call_args = ""
    req_args = [a for a in ep["args"] if a["req"] and not a.get("col")]
    sample = {"VARCHAR": "'…'", "BIGINT": "1", "BOOLEAN": "true", "TIMESTAMPTZ": "TIMESTAMPTZ '2026-11-01'"}
    if fan and fan["parent"] is None:
        call_args = f"{fan['arg']} := '{example_id(ep)}'"
    extra = [f"{a['n']} := {example_value(ep, a, sample)}" for a in req_args]
    if extra:
        call_args = ", ".join([x for x in [call_args] if x] + extra)
    call = f"{q}({call_args})"
    group = next((c for c in ("status", "type", "currency", "brand", "category", "object") if c in cols
                  and cols[c]["k"] == "str"), None)
    title = title_of(ep["name"]).lower()
    if ep["mode"] in ("single", "retrieve", "sub"):
        show = [c for c in cols if cols[c]["k"] in ("id", "key", "str", "time", "int", "money", "bool")][:4] or ["raw"]
        sql = f"SELECT {', '.join(show)} FROM {call}"
        desc = f"Key fields of the {title} ({ep['path']})"
        prompt = f"Show the key fields of the Stripe {title} ({', '.join(show)})."
        return {"sql": sql, "description": desc, "prompt": prompt, "reference": sql}
    if group:
        order = "n DESC, " + group
        sql = f"SELECT {group}, count(*) AS n FROM {call} GROUP BY {group} ORDER BY {order}"
        desc = f"Count {title} by {group}"
        prompt = f"How many Stripe {title} are there per {group}?"
        return {"sql": sql, "description": desc, "prompt": prompt,
                "reference": f"SELECT {group}, count(*) AS n FROM {call} GROUP BY {group} ORDER BY {group}"}
    show = [c for c in cols if cols[c]["k"] in ("id", "key", "str", "ref", "time", "money", "int")][:3] or ["raw"]
    if "created" in cols:
        sql = f"SELECT {', '.join(show)} FROM {call} ORDER BY created DESC LIMIT 10"
        desc = f"The ten most recent {title}"
        prompt = f"List the ten most recently created Stripe {title} ({', '.join(show)})."
        ref = f"SELECT {', '.join(show)} FROM {call} ORDER BY created DESC LIMIT 10"
    else:
        sql = f"SELECT {', '.join(show)} FROM {call} ORDER BY {show[0]} LIMIT 10"
        desc = f"The first ten {title} by {show[0]}"
        prompt = f"List the first ten Stripe {title} by {show[0]} ({', '.join(show)})."
        ref = sql
    return {"sql": sql, "description": desc, "prompt": prompt, "reference": ref}


