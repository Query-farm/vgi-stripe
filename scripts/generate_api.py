def clean(text: str | None) -> str:
    """Spec Markdown/HTML → one plain line."""
    t = html.unescape(text or "")
    t = re.sub(r"<[^>]+>", " ", t)
    t = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", t)
    t = t.replace("`", "").replace("*", "")
    return " ".join(t.split()).strip()


def first_sentence(text: str, limit: int = 200) -> str:
    t = clean(text)
    m = re.match(r"(.+?[.!?])(\s|$)", t)
    s = m.group(1) if m else t
    if len(s) > limit:
        s = s[: limit - 1].rsplit(" ", 1)[0].rstrip(",;:") + "…"
    return s


def shorten(text: str, limit: int) -> str:
    if len(text) <= limit:
        return text
    if limit < 8:
        return text[:limit]
    return text[: limit - 1].rsplit(" ", 1)[0].rstrip(",;:(") + "…"


def singular(seg: str) -> str:
    if seg in SINGULAR_FIX:
        return SINGULAR_FIX[seg]
    if seg.endswith("ies"):
        return seg[:-3] + "y"
    if seg.endswith("sses"):
        return seg[:-2]
    if seg.endswith("s") and not seg.endswith("ss"):
        return seg[:-1]
    return seg


def title_of(name: str) -> str:
    words = name.split("_")
    fix = {"id": "ID", "ids": "IDs", "3d": "3D", "pdf": "PDF", "sigma": "Sigma"}
    return " ".join(fix.get(w, w.capitalize()) for w in words)


class Spec:
    def __init__(self, path: Path):
        self.raw = json.loads(path.read_text())
        self.S = self.raw["components"]["schemas"]
        self.version = self.raw["info"]["version"]

    def deref(self, x: dict) -> dict:
        seen = 0
        while isinstance(x, dict) and "$ref" in x:
            x = self.S[x["$ref"].split("/")[-1]]
            seen += 1
            if seen > 20:
                break
        return x

    def ref_name(self, x: dict) -> str | None:
        return x["$ref"].split("/")[-1] if isinstance(x, dict) and "$ref" in x else None


# --------------------------------------------------------------------------- columns


def scalar_kind(spec: Spec, p: dict) -> str | None:
    """A column kind for a scalar property schema, or None if not scalar."""
    p = spec.deref(p)
    t = p.get("type")
    if t == "string":
        return "str"
    if t == "integer":
        return "time" if p.get("format") == "unix-time" else "int"
    if t == "number":
        return "num"
    if t == "boolean":
        return "bool"
    return None


def is_expandable(p: dict) -> bool:
    return "x-expansionResources" in p or (
        "anyOf" in p and any(v.get("type") == "string" for v in p["anyOf"]) and any("$ref" in v for v in p["anyOf"])
    )


def struct_fields(spec: Spec, p: dict) -> list[list[str]] | None:
    """A small, flat object (all scalar props, at most 6) becomes a STRUCT; else None."""
    if "anyOf" in p:
        return None
    o = spec.deref(p)
    if o.get("type") != "object" or not o.get("properties") or o.get("additionalProperties"):
        return None
    props = o["properties"]
    if len(props) > 6:
        return None
    out = []
    for k, v in props.items():
        if is_expandable(v):
            return None
        sk = scalar_kind(spec, v)
        if sk is None or (spec.deref(v).get("type") == "object"):
            return None
        out.append([k, sk])
    return out


def column_for(spec: Spec, name: str, p: dict, siblings: dict) -> list[dict]:
    """Columns for one top-level property."""
    desc = first_sentence(p.get("description") or spec.deref(p).get("description") or "", 160)
    if name == "metadata":
        return [{"n": name, "k": "meta", "d": desc or "Your key/value metadata on the object."}]
    if is_expandable(p):
        return [{"n": name, "k": "ref", "d": desc}]
    d = spec.deref(p)
    if "anyOf" in p and not is_expandable(p):
        variants = [spec.deref(v) for v in p["anyOf"]]
        kinds = {scalar_kind(spec, v) for v in variants}
        if len(kinds) == 1 and None not in kinds:
            k = kinds.pop()
            return [{"n": name, "k": k, "d": desc}]
        return [{"n": name, "k": "json", "d": desc}]
    t = d.get("type")
    if t == "string":
        col = {"n": name, "k": "str", "d": desc}
        if d.get("enum"):
            col["enum"] = d["enum"]
        return [col]
    if t == "integer":
        if d.get("format") == "unix-time":
            return [{"n": name, "k": "time", "d": desc}]
        has_currency = "currency" in siblings
        if has_currency and AMOUNT.match(name) and not NOT_AMOUNT.search(name):
            if f"{name}_decimal" in siblings:
                return [{"n": name, "k": "int", "d": desc + " (minor units)"}]
            return [{"n": name, "k": "money", "d": desc}]
        return [{"n": name, "k": "int", "d": desc}]
    if t == "number":
        return [{"n": name, "k": "num", "d": desc}]
    if t == "boolean":
        return [{"n": name, "k": "bool", "d": desc}]
    if t == "array":
        it = spec.deref(d.get("items", {}))
        if it.get("type") == "string" and "anyOf" not in d.get("items", {}):
            return [{"n": name, "k": "strList", "d": desc}]
        return [{"n": name, "k": "json", "d": desc}]
    if t == "object":
        sf = struct_fields(spec, p)
        if sf:
            return [{"n": name, "k": "struct", "f": sf, "d": desc}]
        return [{"n": name, "k": "json", "d": desc}]
    return [{"n": name, "k": "json", "d": desc}]


def item_properties(spec: Spec, item_schema: dict) -> tuple[dict, bool, list[str]]:
    """Properties of a list item (intersection for anyOf/polymorphic items)."""
    if "anyOf" in item_schema:
        variants = [spec.deref(v) for v in item_schema["anyOf"]]
        names = [spec.ref_name(v) or "?" for v in item_schema["anyOf"]]
        common = set(variants[0].get("properties", {}))
        for v in variants[1:]:
            common &= set(v.get("properties", {}))
        props = {k: variants[0]["properties"][k] for k in variants[0].get("properties", {}) if k in common}
        return props, True, names
    s = spec.deref(item_schema)
    return s.get("properties", {}), False, [spec.ref_name(item_schema) or ""]


def build_columns(spec: Spec, props: dict, polymorphic: bool, key: str | None, obj: str = "") -> list[dict]:
    secret = SECRET_FIELDS | OBJECT_SECRET_FIELDS.get(obj, set())
    props = {k: v for k, v in props.items() if k not in secret}
    cols: list[dict] = []
    if "id" in props:
        cols.append({"n": "id", "k": "id", "d": first_sentence(props["id"].get("description", "Unique identifier."))})
    if key and key != "id":
        kd = f"Parent {key.replace('_', ' ')} id this row belongs to."
        cols.append({"n": key, "k": "key", "d": kd, **({"p": key} if key in props else {})})
    if polymorphic and "object" in props:
        cols.append({"n": "object", "k": "str", "d": "Object type of this row (the list mixes several types)."})
    for name, p in props.items():
        if name in ("id", "object") or name == key:
            continue
        cols.extend(column_for(spec, name, p, props))
    # *_decimal companions must not collide with real properties.
    names = {c["n"] for c in cols}
    for c in cols:
        if c["k"] == "money" and f"{c['n']}_decimal" in names:
            c["k"] = "int"
    return cols


SQL_SCALAR = {"str": "VARCHAR", "int": "BIGINT", "num": "DOUBLE", "bool": "BOOLEAN", "time": "TIMESTAMP WITH TIME ZONE"}


def sql_type(c: dict) -> str:
    k = c["k"]
    if k == "struct":
        return "STRUCT(" + ", ".join(f'"{n}" {SQL_SCALAR[t]}' for n, t in c["f"]) + ")"
    return {"id": "VARCHAR", "key": "VARCHAR", "ref": "VARCHAR", "meta": "MAP(VARCHAR, VARCHAR)",
            "strList": "VARCHAR[]", "json": "JSON", "money": "BIGINT"}.get(k) or SQL_SCALAR[k]


def schema_json(cols: list[dict]) -> str:
    """The exact vgi.result_columns_schema the worker publishes for these columns (src/stripe/api.ts)."""
    out = []
    for c in cols:
        if c["k"] == "money":
            out.append({"name": c["n"], "type": "BIGINT", "description": f"{c['d']} (minor units)"})
            out.append({"name": f"{c['n']}_decimal", "type": "DECIMAL(38,3)",
                        "description": "Same amount in major units (exact)."})
        else:
            out.append({"name": c["n"], "type": sql_type(c), "description": c["d"]})
    out.append({"name": "raw", "type": "JSON",
                "description": "The whole object as JSON, expansions included, secrets redacted."})
    return json.dumps(out, separators=(",", ":"), ensure_ascii=False)


def type_len(c: dict) -> int:
    base = {"id": 7, "key": 7, "str": 7, "ref": 7, "time": 24, "int": 6, "num": 6, "bool": 7, "meta": 21,
            "strList": 9, "json": 4, "money": 6}
    if c["k"] == "struct":
        return 9 + sum(len(f[0]) + 10 for f in c["f"])
    return base.get(c["k"], 8)


def budget_docs(cols: list[dict]) -> list[dict]:
    """Shorten column docs so vgi.result_columns_schema fits the tag budget (raw column included)."""
    def size(limit: int | None) -> int:
        trial = [{**c, "d": c["d"] if limit is None else shorten(c["d"], limit)} for c in cols]
        return len(schema_json(trial))

    if size(None) <= TAG_BUDGET:
        return cols
    for limit in (140, 120, 100, 80, 64, 50, 40):
        if size(limit) <= TAG_BUDGET:
            for c in cols:
                c["d"] = shorten(c["d"], limit)
            return cols
    # Too wide even with 40-character docs: drop JSON/STRUCT/list columns (they stay in `raw`),
    # last first, then shorten further, then drop trailing scalar columns.
    keep = {"id", "key", "created", "currency", "status", "customer", "amount", "metadata", "livemode", "type"}
    while size(40) > TAG_BUDGET:
        wide = [c for c in cols if c["k"] in ("json", "struct", "strList")]
        if not wide:
            break
        cols.remove(wide[-1])
    limit = 40
    for limit in (40, 32, 24):
        if size(limit) <= TAG_BUDGET:
            break
    while size(limit) > TAG_BUDGET:
        victims = [c for c in cols if c["n"] not in keep and c["k"] not in ("id", "key")]
        if not victims:
            break

        def worth(c: dict) -> int:  # drop free text first, then flags/counts, keep money/time/enums/refs
            if c["k"] in ("money", "time"):
                return 4
            if c["k"] == "ref" or c.get("enum"):
                return 3
            if c["k"] in ("int", "num", "bool", "meta"):
                return 2
            return 1

        cols.remove(min(reversed(victims), key=worth))
    for c in cols:
        c["d"] = shorten(c["d"], limit)
    return cols


def fill_empty_docs(cols: list[dict], obj: str) -> None:
    for c in cols:
        if not c["d"]:
            c["d"] = f"The {c['n'].replace('_', ' ')} field of the {obj} object."
        if c.get("enum"):
            vals = c["enum"]
            listed = ", ".join(vals[:8]) + (", …" if len(vals) > 8 else "")
            text = f"{c['d'].rstrip('.…')}. One of: {listed}."
            if len(text) <= 200:
                c["d"] = text


TYPE_WORDS = [(re.compile(r"\b[Aa] positive integer\b"), "A positive whole number"),
              (re.compile(r"\binteger\b", re.I), "whole number"),
              (re.compile(r"\btimestamp\b", re.I), "time"),
              (re.compile(r"\bboolean\b", re.I), "flag"),
              (re.compile(r"\bstring\b", re.I), "text")]


def no_type_words(text: str) -> str:
    """Argument docs must not restate a data type (vgi-lint VGI313)."""
    for rx, repl in TYPE_WORDS:
        text = rx.sub(repl, text)
    return text


# --------------------------------------------------------------------------- params


def param_shape(spec: Spec, q: dict) -> dict:
    s = q.get("schema", {})
    variants = s.get("anyOf", [s])
    out: dict = {"types": set(), "keys": [], "enum": None, "subs": {}}
    for v in variants:
        v = spec.deref(v)
        t = v.get("type")
        if t:
            out["types"].add(t)
        if t == "object" and v.get("properties"):
            out["keys"] = sorted(v["properties"])
            out["subs"] = {k: spec.deref(x) for k, x in v["properties"].items()}
        if t == "array":
            it = spec.deref(v.get("items", {}))
            out["item_enum"] = it.get("enum")
        if v.get("enum"):
            out["enum"] = v["enum"]
        if t == "integer" and v.get("format") == "unix-time":
            out["unix"] = True
    return out


def arg_type(sch: dict) -> str | None:
    t = sch.get("type")
    if t == "string":
        return "VARCHAR"
    if t == "boolean":
        return "BOOLEAN"
    if t == "integer":
        return "TIMESTAMPTZ" if sch.get("format") == "unix-time" else "BIGINT"
    return None


def safe_arg(name: str) -> str:
    return f"{name}_value" if name in RESERVED_ARGS or name in COMMON_ARGS else name


# --------------------------------------------------------------------------- endpoints


def classify(spec: Spec) -> dict:
    lists, searches, objects = {}, {}, {}
    for path, item in sorted(spec.raw["paths"].items()):
        op = item.get("get")
        if not op:
            continue
        content = op["responses"]["200"]["content"]
        ctype = next(iter(content))
        sch = content[ctype]["schema"]
        if ctype != "application/json":
            objects[path] = ("binary", sch, op)
            continue
        r = spec.deref(sch)
        props = r.get("properties", {})
        obj_enum = props.get("object", {}).get("enum")
        if "data" in props and obj_enum in (["list"], ["search_result"]):
            (searches if obj_enum == ["search_result"] else lists)[path] = (props["data"]["items"], op)
        else:
            objects[path] = (sch if "anyOf" not in sch else sch["anyOf"][0], sch, op)
    return {"lists": lists, "searches": searches, "objects": objects}


def placement(path: str) -> tuple[str, str, str]:
    """(schema, category, function name) for an endpoint path."""
    rest = path[len("/v1/"):]
    schema = category = prefix = None
    stripped = rest
    for pre, sch, name_prefix, cat in NAMESPACES:
        if rest.startswith(pre):
            schema, category, prefix = sch, cat, name_prefix
            stripped = rest[len(pre):] if pre.endswith("/") else rest
            if not pre.endswith("/"):
                prefix = ""
            break
    if schema is None:
        top = rest.split("/")[0]
        if top not in TOP:
            raise SystemExit(f"generate_api: no schema placement for {path}; add it to TOP or NAMESPACES")
        schema, category = TOP[top]
        prefix = ""
    if path in NAME_OVERRIDES:
        return schema, category, NAME_OVERRIDES[path]
    segs = [s for s in stripped.split("/") if s]
    parts: list[str] = []
    for i, s in enumerate(segs):
        if s.startswith("{"):
            continue
        nxt_is_param = i + 1 < len(segs) and segs[i + 1].startswith("{")
        has_child = any(not x.startswith("{") for x in segs[i + 1:])
        parts.append(singular(s) if nxt_is_param and has_child else s)
    name = prefix + "_".join(parts)
    return schema, category, name


def category_override(path: str, schema: str, category: str) -> str:
    if schema == "issuing" and any(x in path for x in ("authorizations", "transactions", "disputes", "settlements")):
        return "spend"
    if schema == "treasury" and "financial_accounts" in path:
        return "accounts"
    if path.startswith("/v1/billing/") and "portal" in path:
        return "customers"
    if path == "/v1/test_helpers/test_clocks":
        return "subscriptions"
    if path.startswith("/v1/tax/") and schema == "tax":
        return "tax"
    if path.startswith(("/v1/tax_rates", "/v1/tax_codes", "/v1/tax_ids")):
        return "tax_reference"
    return category


def build(spec: Spec) -> tuple[list[dict], list[tuple[str, str]], list[str]]:
    cls = classify(spec)
    lists, searches, objects = cls["lists"], cls["searches"], cls["objects"]
    endpoints: list[dict] = []
    excluded: list[tuple[str, str]] = sorted(EXCLUDE.items())
    folded: list[str] = []
    list_paths = set(lists)

    def object_name(item: dict) -> str:
        if "anyOf" in item:
            return " / ".join(spec.ref_name(v) or "?" for v in item["anyOf"])
        return spec.ref_name(item) or "object"

    def params_and_args(path: str, op: dict, cols: list[dict], skip: set[str], single: bool = False) -> dict:
        # A single-object GET is one request: its parameters are arguments, never WHERE pushdown.
        colmap = {} if single else {c["n"]: c for c in cols}
        params, ranges, args, all_params = [], [], [], []
        required_with_column = []
        for q in op.get("parameters", []):
            if q["in"] != "query":
                continue
            name = q["name"]
            all_params.append(name)
            if name in PAGING or name in skip or name in SECRET_FIELDS:
                continue
            sh = param_shape(spec, q)
            req = bool(q.get("required"))
            col = colmap.get(name)
            types = sh["types"]
            desc = no_type_words(first_sentence(q.get("description") or "", 180))
            # time ranges
            if "object" in types and set(sh["keys"]) <= {"gt", "gte", "lt", "lte"} and sh["keys"]:
                if col and col["k"] == "time":
                    ranges.append({"c": name, "p": name})
                    continue
                if not req:
                    continue  # a range on a field we do not expose: params := only
            # array params: ids[] → id, lookup_keys[] → lookup_key, types[] → type
            if types == {"array"}:
                target = "id" if name == "ids" else singular(name)
                if target in colmap and colmap[target]["k"] in ("id", "str", "ref"):
                    existing = next((p for p in params if p["c"] == target), None)
                    if existing:
                        existing["arr"] = name
                    else:
                        params.append({"c": target, "p": name, "k": "string", "arr": name, "only": True})
                continue
            scalar_types = types - {"object"}
            if col and not req and scalar_types and col["k"] in ("id", "str", "ref", "key") and "string" in types:
                p = {"c": name, "p": name, "k": "string"}
                if sh["enum"]:
                    p["ch"] = sh["enum"]
                existing = next((x for x in params if x["c"] == name), None)
                if existing:  # an array param was seen first
                    existing.update({k: v for k, v in p.items() if k != "c"})
                    existing.pop("only", None)
                else:
                    params.append(p)
                continue
            if col and not req and col["k"] == "bool" and "boolean" in types:
                params.append({"c": name, "p": name, "k": "bool"})
                continue
            # anything else scalar → a named argument; objects with scalar keys → name_key args
            if scalar_types and len(scalar_types) == 1 and "object" not in types:
                t = arg_type({"type": next(iter(scalar_types)), **({"format": "unix-time"} if sh.get("unix") else {})})
                if t:
                    a = {"n": safe_arg(name), "p": name, "t": t, "d": desc or f"Stripe query parameter {name}.",
                         "req": req}
                    if sh["enum"]:
                        a["ch"] = sh["enum"]
                    if col and col["k"] in ("str", "ref", "key") and t == "VARCHAR":
                        a["col"] = name
                    args.append(a)
                continue
            if types == {"object"} and sh["subs"]:
                for sub, ss in sh["subs"].items():
                    t = arg_type(ss)
                    if not t:
                        continue
                    a = {"n": safe_arg(f"{name}_{sub}"), "p": f"{name}[{sub}]", "t": t,
                         "d": no_type_words(first_sentence(ss.get("description") or desc or f"Stripe parameter {name}[{sub}].", 180)),
                         "req": False}
                    if ss.get("enum"):
                        a["ch"] = ss["enum"]
                    if (path, f"{name}[{sub}]") in ARG_DEFAULTS:
                        a["def"] = ARG_DEFAULTS[(path, f"{name}[{sub}]")]
                    args.append(a)
                if req:
                    required_with_column.append(name)
        return {"params": params, "ranges": ranges, "args": args, "query_params": sorted(all_params),
                "required_objects": required_with_column}

    def finish(ep: dict, cols: list[dict], obj: str) -> dict:
        ep["columns"] = cols
        return ep

    # ---- lists
    for path, (item, op) in sorted(lists.items()):
        if path in EXCLUDE:
            continue
        schema, category, name = placement(path)
        category = category_override(path, schema, category)
        pparams = re.findall(r"\{(\w+)\}", path)
        props, poly, _ = item_properties(spec, item)
        obj = object_name(item)
        fanout = None
        key = None
        if pparams:
            parent_path = path[: path.index("{" + pparams[0] + "}") + len(pparams[0]) + 2]
            pl, pq, key = PATH_PARENTS[parent_path]
            fanout = {"key": key, "arg": f"{key}_id", "mode": "list", "child": path, "pathParam": pparams[0],
                      "parent": pl, "parentQuery": pq}
            if path in PARENT_FIELDS:
                fanout["fromParent"] = PARENT_FIELDS[path]
        else:
            for q in op.get("parameters", []):
                if q["in"] == "query" and q.get("required") and (path, q["name"]) in PARENT_LISTS:
                    pl, pq = PARENT_LISTS[(path, q["name"])]
                    key = q["name"]
                    fanout = {"key": key, "arg": f"{key}_id", "mode": "list", "child": path, "queryParam": key,
                              "parent": pl, "parentQuery": pq}
        cols = build_columns(spec, props, poly, key, obj)
        fill_empty_docs(cols, obj)
        cols = budget_docs(cols)
        skip = {fanout["queryParam"]} if fanout and "queryParam" in fanout else set()
        if fanout and "fromParent" in fanout:
            skip |= set(fanout["fromParent"])
        pa = params_and_args(path, op, cols, skip)
        retrieve = None
        if not pparams:
            for cand, (osch, _, oop) in objects.items():
                if re.fullmatch(re.escape(path) + r"/\{\w+\}", cand):
                    retrieve = cand
        else:
            for cand in objects:
                if re.fullmatch(re.escape(path) + r"/\{\w+\}", cand):
                    retrieve = cand
        if retrieve:
            folded.append(retrieve)
        status_all = any(
            q["name"] == "status" and "all" in (param_shape(spec, q)["enum"] or []) for q in op.get("parameters", [])
        )
        search = path + "/search" if path + "/search" in searches else None
        ep = {
            "schema": schema, "name": name, "category": category, "path": path, "mode": "list", "object": obj,
            "summary": first_sentence(op.get("description") or op.get("summary") or "", 300),
            "detail": clean(op.get("description") or "")[:1200],
            "retrieve": retrieve, "search": search, "fanout": fanout,
            "paging": {"limit": any(q["name"] == "limit" for q in op.get("parameters", [])),
                       "cursor": any(q["name"] == "starting_after" for q in op.get("parameters", []))},
            "baseQuery": {"status": "all"} if status_all else {},
            **pa,
        }
        endpoints.append(finish(ep, cols, obj))

    # ---- searches are folded into their list function (search := …)
    for path in searches:
        folded.append(path)

    # ---- objects without a list: singletons, retrieve-only, sub-objects
    for path, (osch, full, op) in sorted(objects.items()):
        if path in EXCLUDE or path in folded:
            continue
        if osch == "binary":
            excluded.append((path, "Binary response, not JSON."))
            continue
        pparams = re.findall(r"\{(\w+)\}", path)
        schema, category, name = placement(path)
        category = category_override(path, schema, category)
        s = spec.deref(osch)
        props = s.get("properties", {})
        obj = spec.ref_name(osch) or "object"
        fanout = None
        key = None
        if not pparams:
            mode = "single"
        elif path in RETRIEVE_ONLY_KEYS:
            key = "id"
            mode = "retrieve"
            arg = f"{RETRIEVE_ONLY_KEYS[path]}_id"
            fanout = {"key": "id", "arg": arg, "mode": "object", "child": path, "pathParam": pparams[0],
                      "parent": None, "parentQuery": {}}
            name = name if name.endswith("s") else name + "s"
        elif len(pparams) == 1:
            parent_path = path[: path.index("{" + pparams[0] + "}") + len(pparams[0]) + 2]
            if parent_path not in PATH_PARENTS:
                excluded.append((path, "Retrieve by id with no generated parent: use stripe.api.get."))
                continue
            pl, pq, key = PATH_PARENTS[parent_path]
            mode = "sub"
            fanout = {"key": key, "arg": f"{key}_id", "mode": "object", "child": path, "pathParam": pparams[0],
                      "parent": pl, "parentQuery": pq}
        else:
            if path not in EXCLUDE:
                excluded.append((path, "Retrieve by two ids: `WHERE id = …` on the nested list function, or stripe.api.get."))
            continue
        cols = build_columns(spec, props, False, key if key != "id" else None, obj)
        fill_empty_docs(cols, obj)
        cols = budget_docs(cols)
        pa = params_and_args(path, op, cols, set(SECRET_FIELDS), single=True)
        ep = {
            "schema": schema, "name": name, "category": category, "path": path, "mode": mode, "object": obj,
            "summary": first_sentence(op.get("description") or op.get("summary") or "", 300),
            "detail": clean(op.get("description") or "")[:1200],
            "retrieve": None, "search": None, "fanout": fanout,
            "paging": {"limit": False, "cursor": False}, "baseQuery": {}, **pa,
        }
        endpoints.append(finish(ep, cols, obj))

    # two-id retrieves under a generated nested list are folded into its id pushdown
    by_path = {e["path"]: e for e in endpoints}
    for path in list(objects):
        if path in folded or path in EXCLUDE or any(e["path"] == path for e in endpoints):
            continue
        parent = re.sub(r"/\{\w+\}$", "", path)
        if parent in by_path and by_path[parent]["mode"] == "list":
            by_path[parent]["retrieve"] = path
            folded.append(path)
            excluded[:] = [x for x in excluded if x[0] != path]
    endpoints.sort(key=lambda e: (e["schema"], e["name"]))
    names = [(e["schema"], e["name"]) for e in endpoints]
    dupes = {n for n in names if names.count(n) > 1}
    if dupes:
        raise SystemExit(f"generate_api: duplicate function names {sorted(dupes)}")
    return endpoints, sorted(set(excluded)), sorted(set(folded))


