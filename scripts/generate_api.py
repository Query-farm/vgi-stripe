def write_outputs(spec: Spec, endpoints: list[dict], excluded, folded, get_paths: list[str], check: bool) -> int:
    ids = json.loads((ROOT / "test" / "fixtures" / "api-example-ids.json").read_text()) \
        if (ROOT / "test" / "fixtures" / "api-example-ids.json").exists() else {}
    EXAMPLE_IDS.update(ids)
    for ep in endpoints:
        ex = pick_example(ep)
        ep["example"] = {"sql": ex["sql"], "description": ex["description"]}
        ep["task"] = {"name": f"api_{ep['schema']}_{ep['name']}", "prompt": ex["prompt"], "reference_sql": ex["reference"]}
    out = {
        "generated_by": "scripts/generate_api.py",
        "spec": json.loads((SPEC_DIR / "source.json").read_text()),
        "schemas": {k: {"title": v[0], "description": v[1],
                        "categories": [{"name": c, "title": t, "description": d} for c, (t, d) in v[2].items()]}
                    for k, v in SCHEMAS.items()},
        "get_paths": get_paths,
        "endpoints": endpoints,
    }
    files = {
        OUT_DIR / "endpoints.json": json.dumps(out, indent=1, sort_keys=True, ensure_ascii=False) + "\n",
        OUT_DIR / "EXCLUDED.md": excluded_md(spec, endpoints, excluded, folded),
    }
    tasks = "\n".join(
        f"  - name: {ep['task']['name']}\n    reference_sql: {json.dumps(ep['task']['reference_sql'])}"
        for ep in endpoints
    )
    agent = AGENT_TESTS.read_text()
    block = f"{GEN_BEGIN}\n{tasks}\n{GEN_END}"
    if GEN_BEGIN in agent:
        agent = re.sub(re.escape(GEN_BEGIN) + r".*?" + re.escape(GEN_END), lambda _: block, agent, flags=re.S)
    else:
        agent = agent.rstrip("\n") + "\n" + block + "\n"
    files[AGENT_TESTS] = agent
    changed = 0
    for p, text in files.items():
        old = p.read_text() if p.exists() else None
        if old != text:
            changed += 1
            if check:
                print(f"out of date: {p.relative_to(ROOT)}", file=sys.stderr)
            else:
                p.parent.mkdir(parents=True, exist_ok=True)
                p.write_text(text)
    return changed


def excluded_md(spec: Spec, endpoints, excluded, folded) -> str:
    gets = sorted(p for p, v in spec.raw["paths"].items() if "get" in v)
    by_path = {e["path"]: e for e in endpoints}
    retrieve_of = {e["retrieve"]: e for e in endpoints if e.get("retrieve")}
    search_of = {e["search"]: e for e in endpoints if e.get("search")}
    lines = [
        "<!-- generated by scripts/generate_api.py from spec/stripe-openapi/spec3.json; do not edit -->",
        "# Stripe GET endpoints: coverage",
        "",
        f"Stripe API {spec.version}, {len(gets)} GET endpoints. Every one is accounted for below: generated as a "
        "table function, folded into a generated function (retrieve-by-id → `WHERE id = …` pushdown, search → "
        "`search :=`), or excluded with the reason. Non-GET operations (create/update/delete/confirm/capture, "
        "`test_helpers/*` simulations) are writes and are never generated. Stripe's v2 API (`/v2/…`) is not in "
        "`spec3.json` (it has its own spec, auth and pagination) and is not covered; `stripe.api.get` accepts "
        "`/v1/` paths only.",
        "",
        "| GET endpoint | Covered by |",
        "|---|---|",
    ]
    exc = dict(excluded)
    for p in gets:
        if p in by_path:
            e = by_path[p]
            how = f"`stripe.{e['schema']}.{e['name']}`"
        elif p in retrieve_of:
            e = retrieve_of[p]
            how = f"`WHERE id = …` on `stripe.{e['schema']}.{e['name']}`"
        elif p in search_of:
            e = search_of[p]
            how = f"`search := …` on `stripe.{e['schema']}.{e['name']}`"
        elif p in exc:
            how = f"**excluded**: {exc[p]}"
        else:
            raise SystemExit(f"generate_api: GET {p} is neither generated nor excluded")
        lines.append(f"| `{p}` | {how} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if the committed output is stale")
    args = ap.parse_args()
    spec = Spec(SPEC_DIR / "spec3.json")
    endpoints, excluded, folded = build(spec)
    get_paths = sorted(p for p, v in spec.raw["paths"].items() if "get" in v and p not in ("/v1/quotes/{quote}/pdf",))
    changed = write_outputs(spec, endpoints, excluded, folded, get_paths, args.check)
    counts: dict[str, int] = {}
    for e in endpoints:
        counts[e["schema"]] = counts.get(e["schema"], 0) + 1
    print(f"{len(endpoints)} generated functions: {counts}; {len(excluded)} excluded; {len(folded)} folded",
          file=sys.stderr)
    if args.check and changed:
        sys.exit(1)


if __name__ == "__main__":
    main()
